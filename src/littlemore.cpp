// The struct layouts of the header are designed for 64-bit ABIs (see "Platforms" there): no hidden padding, so
// sizeof() is the end of the last field and the struct_size protocol can check field boundaries exactly.
static_assert(sizeof(void *) == 8, "littlemore supports 64-bit platforms only (see littlemore.h)");
static_assert(sizeof(lm_model_options) == offsetof(lm_model_options, use_mmap) + sizeof(int32_t), "padding in lm_model_options");
