// Owns a llama_model until it is handed to an lm_model (so an exception on the way cannot leak it).
struct llama_model_deleter {
    void operator()(llama_model * m) const { llama_model_free(m); }
};

// Marks the calling thread as the one generating on `s` while it holds the session lock; clears it on exit, also
// when the generation ends with an error or an exception.
struct owner_scope {
    lm_session * s;
    explicit owner_scope(lm_session * session) : s(session) { s->owner.store(std::this_thread::get_id()); }
    ~owner_scope() { s->owner.store(std::thread::id()); }
};

// True when the calling thread is the one currently generating on this session (i.e. we are inside its token callback).
bool is_reentrant(const lm_session * s) {
    return s->owner.load() == std::this_thread::get_id();
}

// Error for an API call made from inside the session's own token callback: refused, because the session lock is held by the running generation (calling back would deadlock).
lm_status reentrant_error(const char * fn) {
    return fail(LM_ERR_REENTRANT, std::string(fn) +
                                      ": called from inside this session's own token callback; it is refused (the "
                                      "running generation continues). Return non-zero from the callback to stop, "
                                      "then call again after the outer call has returned");
}

// The shared tail of lm_chat and lm_generate: refuse a re-entrant call, then generate under the session lock.
lm_status locked_run(lm_session * session, const std::string & prompt, const lm_sampling & s, lm_token_cb cb, void * user,
                     const char * fn) {
    if (is_reentrant(session)) {
        return reentrant_error(fn);
    }
    std::lock_guard<std::mutex> lock(session->mu);
    owner_scope owner(session);
    return run(session, prompt, s, cb, user, fn);
}

