static_assert(offsetof(lm_model_options, devices) == offsetof(lm_model_options, reserved0) + sizeof(int32_t), "hole in lm_model_options");
static_assert(sizeof(lm_status) == 4, "lm_status must be 32-bit (documented for FFI)");
static_assert(LM_SEED_RANDOM == LLAMA_DEFAULT_SEED, "LM_SEED_RANDOM is passed through as llama.cpp's random-seed value");

