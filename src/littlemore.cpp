// End offsets of every field of each public struct, in order (the last one is sizeof(T), as the static_asserts
// above guarantee). A caller's struct_size must be one of them, or larger than sizeof(T): an older caller's
// struct ends at the end of its last field because no struct has hidden tail padding.
#define LM_END(T, f) (offsetof(T, f) + sizeof(((T *) nullptr)->f))
template <typename T> struct field_ends;
template <> struct field_ends<lm_model_options> {
    static constexpr size_t v[] = { LM_END(lm_model_options, struct_size), LM_END(lm_model_options, n_gpu_layers),
                                    LM_END(lm_model_options, reserved0), LM_END(lm_model_options, devices),
                                    LM_END(lm_model_options, vram_budget), LM_END(lm_model_options, fit_n_ctx),
                                    LM_END(lm_model_options, use_mmap) };
};
template <> struct field_ends<lm_session_options> {
    static constexpr size_t v[] = { LM_END(lm_session_options, struct_size), LM_END(lm_session_options, n_ctx),
                                    LM_END(lm_session_options, n_threads), LM_END(lm_session_options, n_batch),
                                    LM_END(lm_session_options, reserved0) };
};
template <> struct field_ends<lm_sampling> {
    static constexpr size_t v[] = { LM_END(lm_sampling, struct_size), LM_END(lm_sampling, temperature),
                                    LM_END(lm_sampling, top_k), LM_END(lm_sampling, top_p), LM_END(lm_sampling, seed),
                                    LM_END(lm_sampling, max_tokens), LM_END(lm_sampling, reserved0) };
};
template <> struct field_ends<lm_model_info> {
    static constexpr size_t v[] = { LM_END(lm_model_info, struct_size), LM_END(lm_model_info, n_layer),
                                    LM_END(lm_model_info, n_gpu_layers), LM_END(lm_model_info, n_ctx_train),
                                    LM_END(lm_model_info, n_vocab), LM_END(lm_model_info, n_embd),
                                    LM_END(lm_model_info, reserved0), LM_END(lm_model_info, size_bytes),
                                    LM_END(lm_model_info, n_params), LM_END(lm_model_info, fit_budget_bytes),
                                    LM_END(lm_model_info, fit_reserve_bytes), LM_END(lm_model_info, fit_layer_bytes),
                                    LM_END(lm_model_info, fit_head_bytes), LM_END(lm_model_info, gpu_devices),
                                    LM_END(lm_model_info, description) };
};
#undef LM_END
static_assert(field_ends<lm_model_options>::v[6] == sizeof(lm_model_options), "field table of lm_model_options");
static_assert(field_ends<lm_session_options>::v[4] == sizeof(lm_session_options), "field table of lm_session_options");
static_assert(field_ends<lm_sampling>::v[6] == sizeof(lm_sampling), "field table of lm_sampling");
static_assert(field_ends<lm_model_info>::v[14] == sizeof(lm_model_info), "field table of lm_model_info");

// True when n is the end of one of T's fields.
template <typename T> bool on_field_boundary(size_t n) {
    for (size_t e : field_ends<T>::v) {
        if (e == n) {
            return true;
        }
    }
    return false;
}

// Reads a caller's options struct into `out` (which holds the defaults on entry), by the header's append-only
// rule:
//   - struct_size smaller than ours: an older caller; it must end on one of our field boundaries (a size that
//     cuts a field in two cannot come from any real header version), then only its fields are copied and our
//     defaults stay for the rest;
//   - larger than ours: a newer caller; accepted only if every byte after our last field (sizeof(T), which is
//     the end of the last known field) is zero, because a non-zero unknown field is a request this library
//     cannot honour and must not ignore silently.
// Reserved fields are checked by the caller of this function (they must be 0).
template <typename T> lm_status read_struct(const T * in, T & out, const char * fn, const char * type) {
    if (!in) {
        return LM_OK;
    }
    const size_t n = in->struct_size;
    if (n < sizeof(T) && !on_field_boundary<T>(n)) {
        return fail(LM_ERR_INVALID_ARG, std::string(fn) + ": " + type + ".struct_size is " + std::to_string(n) +
                                            ", which is not the end of a field; set it to sizeof(" + type +
                                            ") (or use " + type + "_default)");
    }
    if (n > sizeof(T)) {
        const unsigned char * bytes = reinterpret_cast<const unsigned char *>(in);
        for (size_t i = sizeof(T); i < n; ++i) {
            if (bytes[i] != 0) {
                return fail(LM_ERR_UNSUPPORTED, std::string(fn) + ": " + type + " has fields this library (" +
                                                    k_version + ") does not know (struct_size " +
                                                    std::to_string(n) + ", known " + std::to_string(sizeof(T)) +
                                                    ", non-zero byte at offset " + std::to_string(i) +
                                                    "); upgrade the littlemore library");
            }
        }
    }
    std::memcpy(static_cast<void *>(&out), in, std::min(n, sizeof(T)));
    out.struct_size = sizeof(T);
    return LM_OK;
}

// Reserved fields must stay 0 so that a later version can give them a meaning without misreading old callers.
lm_status check_reserved(int64_t value, const char * fn, const char * field) {
    if (value != 0) {
        return fail(LM_ERR_UNSUPPORTED, std::string(fn) + ": " + field + " is reserved and must be 0");
    }
    return LM_OK;
}

